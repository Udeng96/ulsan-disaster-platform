package com.eseict.ulsan.gis.facility.pump;

/**
 * 펌프장 장비의 카테고리.
 *
 * <p>화면에서 같은 종류 끼리 묶어 표출하기 위한 분류.
 * 위치/접두사만 다른 같은 류는 같은 값으로 묶었음
 * (예: 외수위계 / 내수위계 / 맨홀수위 / 태화강수위 / 등 → {@link #WATER_LEVEL}).
 *
 * <p>화면 그룹화는 프론트가 처리 — 백엔드는 enum 값만 노출한다.
 */
public enum EquipmentCategory {

    /** PLC — 펌프장 제어기 자체. 상태값 "통신오류" 만 의미가짐. */
    PLC,

    // --- 펌프 / 모터 -------------------------------------------------------

    /** 원동기펌프 (예: 가상시설0411·가상시설0523 의 원동기펌프1~5). */
    MOTOR_ORIG,

    /** 전동기펌프 (예: 가상시설0411·가상시설0523 의 전동기 펌프1~5). */
    MOTOR_ELEC,

    /** 일반 펌프 — 작은 펌프장 의 메인 펌프 (펌프1/2/3, 배수펌프1/2/3). */
    PUMP_GENERIC,

    /** 지배수펌프. */
    PUMP_SUB_DRAIN,

    /** 드레인펌프. */
    PUMP_DRAIN,

    /** 잡배수펌프 / 흡수정펌프. */
    PUMP_MISC,

    /** 구리스펌프. */
    PUMP_GREASE,

    /** 냉각수 펌프 (공급/리턴/원동기실 냉각수/냉각탑/쿨링타워 등). */
    PUMP_COOLING,

    /** 연료펌프. */
    PUMP_FUEL,

    /** 에어콤푸레샤 / 공기압축기. */
    PUMP_AIR,

    /** 비상발전기 (현재 시드엔 없지만 화면에 등장). */
    EMERGENCY_GEN,

    // --- 설비 / 계측 -------------------------------------------------------

    /** 밸브 (전동밸브 / 토출밸브). */
    VALVE,

    /** 수문 (배수문 / 유입수문 / 자연배수로 / 태화강수문 / 돋질로수문). */
    GATE,

    /** 제진기 / 스크린 (전동기·원동기 위치 무관). */
    SCREEN,

    /** 수위계 (외/내/맨홀/태화강/유수지/유입/집수정/조합수조/원동기실/전동기실). */
    WATER_LEVEL
}
