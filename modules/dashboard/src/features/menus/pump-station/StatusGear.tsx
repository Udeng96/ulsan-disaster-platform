/** equipment state 코드 → 톱니 variant (좌측 카드 + 우측 grid/범례 공통 규칙).
 *  1 켜짐→green · 2 꺼짐→red · 3 오류/4 정비/null 미연동→blue 고장(정비) */
export function gearVariantFromState(state: number | null): FanVariant {
  switch (state) {
    case 1:
      return 'green'
    case 2:
      return 'red'
    default:
      return 'blue'
  }
}

